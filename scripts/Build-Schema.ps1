# Single source of truth: schema/managed-settings.csv + schema/usersettings-metadata.json
# Produces:
#   schema/settings.json                                   (used by Deploy-Schema.ps1)
#   src/DefaultUserSettings.Plugins/Registry/SettingsRegistry.g.cs
# Adding a setting = one CSV line, then re-run this script and Deploy-Schema.ps1.
param([string]$Root = "$PSScriptRoot\..")
$ErrorActionPreference = 'Stop'
$meta = Get-Content "$Root\schema\usersettings-metadata.json" -Raw | ConvertFrom-Json
$rows = Import-Csv "$Root\schema\managed-settings.csv"

# Lookups to tables that a custom lookup column cannot target are stored as GUID text.
$lookupAsText = @{ preferredsolution = 'solution' }

$settings = foreach ($r in $rows) {
  $a = $meta.($r.attribute)
  if (-not $a) { throw "Attribute $($r.attribute) not in usersettings metadata" }
  $s = [ordered]@{
    attribute = $r.attribute; label = $r.label; group = $r.group
    valueColumn = "jhrb_$($r.attribute)"; modeColumn = "jhrb_$($r.attribute)_mode"
  }
  switch ($a.type) {
    'Integer' { $s.kind = 'Integer'; $s.min = $a.min; $s.max = $a.max }
    'String'  { $s.kind = 'String'; $s.maxLength = [int]$a.maxLength }
    'Boolean' { $s.kind = 'Boolean' }
    'Picklist' { $s.kind = 'Choice'; $s.options = $a.options }
    'Uniqueidentifier' { $s.kind = 'GuidText'; $s.maxLength = 36 }
    'Lookup' {
      if ($lookupAsText.ContainsKey($r.attribute)) { $s.kind = 'LookupText'; $s.target = $lookupAsText[$r.attribute]; $s.maxLength = 36 }
      else { $s.kind = 'Lookup'; $s.target = $a.targets[0] }
    }
    default { throw "Unsupported type $($a.type) for $($r.attribute)" }
  }
  [pscustomobject]$s
}
$settings | ConvertTo-Json -Depth 6 | Set-Content "$Root\schema\settings.json" -Encoding utf8

$lines = foreach ($s in $settings) {
  $target = if ($s.target) { "`"$($s.target)`"" } else { 'null' }
  "            new SettingDefinition(`"$($s.attribute)`", `"$($s.valueColumn)`", `"$($s.modeColumn)`", SettingKind.$($s.kind), $target, `"$($s.label)`"),"
}
$cs = @"
// <auto-generated>
// Generated by scripts/Build-Schema.ps1 from schema/managed-settings.csv. Do not edit by hand.
// </auto-generated>
using System.Collections.Generic;

namespace DefaultUserSettings.Plugins.Registry
{
    public static partial class SettingsRegistry
    {
        private static readonly IReadOnlyList<SettingDefinition> _all = new List<SettingDefinition>
        {
$($lines -join "`r`n")
        };
    }
}
"@
$dir = "$Root\src\DefaultUserSettings.Plugins\Registry"
New-Item -ItemType Directory -Force $dir | Out-Null
Set-Content "$dir\SettingsRegistry.g.cs" $cs -Encoding utf8
"settings: $(@($settings).Count)"; $settings | Group-Object kind | % { "  $($_.Name): $($_.Count)" }
