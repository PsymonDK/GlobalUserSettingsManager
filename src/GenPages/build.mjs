// Bundles each generative page into ONE .tsx file (the platform takes a single file per page).
// The page file and every local module it imports (transitively, deps first) are concatenated:
//   - imports from npm packages are merged at the top (one statement per package),
//   - imports of local .ts/.tsx modules are dropped (their code is inlined),
//   - imports of local .json files become `const <name> = <json>;`,
//   - `export` is stripped from shared modules (the page keeps its `export default`).
// Names must therefore be unique across the shared modules. Output: dist/<key>.tsx and dist/<key>.actions.json.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
// schema/settings.json is written by Windows PowerShell 5.1, which adds a byte-order mark.
const readJson = (p) => JSON.parse(readFileSync(p, 'utf8').replace(/^﻿/, ''));
const manifest = readJson(resolve(root, 'pages.json'));
const apis = readJson(resolve(root, 'custom-apis.json'));
const ALLOWED = new Set(['react', '@fluentui/react-components', '@fluentui/react-icons']);
const IMPORT_RE = /^import\s+([\s\S]*?)\s+from\s+['"]([^'"]+)['"];?[ \t]*$/gm;

function resolveLocal(from, spec) {
  const base = resolve(dirname(from), spec);
  for (const p of [base, `${base}.ts`, `${base}.tsx`]) if (existsSync(p) && !p.endsWith('\\') && /\.(tsx?|json)$/.test(p)) return p;
  throw new Error(`${relative(root, from)}: cannot resolve ${spec}`);
}

function parseClause(clause) {
  // Returns { typeOnly, namespace, defaultName, named: [...] }
  let c = clause.trim();
  const typeOnly = c.startsWith('type ');
  if (typeOnly) c = c.slice(5).trim();
  const ns = /^\*\s+as\s+(\w+)$/.exec(c);
  if (ns) return { typeOnly, namespace: ns[1], named: [] };
  let defaultName;
  const m = /^(\w+)\s*(?:,\s*)?(.*)$/s.exec(c);
  if (m && !c.startsWith('{')) { defaultName = m[1]; c = m[2].trim(); }
  const named = c.startsWith('{') ? c.slice(1, c.lastIndexOf('}')).split(',').map((s) => s.trim()).filter(Boolean) : [];
  return { typeOnly, defaultName, named };
}

function bundle(entry) {
  const order = [];
  const seen = new Set();
  const externals = new Map(); // module -> { values:Set, types:Set, namespace?:string }
  const jsonConsts = [];
  const bodies = new Map();

  function visit(file) {
    if (seen.has(file)) return;
    seen.add(file);
    const src = readFileSync(file, 'utf8');
    const deps = [];
    const body = src.replace(IMPORT_RE, (_all, clause, spec) => {
      if (spec.startsWith('.')) {
        const target = resolveLocal(file, spec);
        if (target.endsWith('.json')) {
          const { defaultName } = parseClause(clause);
          if (!defaultName) throw new Error(`${relative(root, file)}: JSON import needs a default name`);
          if (!jsonConsts.some((j) => j.name === defaultName)) jsonConsts.push({ name: defaultName, json: JSON.stringify(readJson(target)) });
        } else deps.push(target);
        return '';
      }
      if (!ALLOWED.has(spec)) throw new Error(`${relative(root, file)}: package ${spec} is not available in generative pages`);
      const p = parseClause(clause);
      const e = externals.get(spec) ?? { values: new Set(), types: new Set() };
      if (p.namespace) e.namespace = p.namespace;
      if (p.defaultName) throw new Error(`${relative(root, file)}: use named or namespace imports for ${spec}`);
      for (const n of p.named) {
        if (p.typeOnly || n.startsWith('type ')) e.types.add(n.replace(/^type\s+/, ''));
        else e.values.add(n);
      }
      externals.set(spec, e);
      return '';
    });
    for (const d of deps) visit(d);
    const isEntry = file === entry;
    const cleaned = (isEntry ? body : body.replace(/^export\s+(?=(?:async\s+)?(?:function|const|let|class|interface|type|enum|abstract)\b)/gm, ''))
      .replace(/^\s*\n/, '');
    if (!isEntry && /^export\s/m.test(cleaned)) throw new Error(`${relative(root, file)}: unsupported export form`);
    bodies.set(file, cleaned);
    order.push(file);
  }
  visit(entry);

  const lines = [];
  for (const [spec, e] of externals) {
    if (e.namespace) lines.push(`import * as ${e.namespace} from '${spec}';`);
    const values = [...e.values].filter((v) => !e.types.has(v)).sort();
    if (values.length) lines.push(`import { ${values.join(', ')} } from '${spec}';`);
    const types = [...e.types].filter((t) => !e.values.has(t)).sort();
    if (types.length) lines.push(`import type { ${types.join(', ')} } from '${spec}';`);
  }
  const parts = [
    `// GENERATED by src/GenPages/build.mjs from ${order.map((f) => relative(root, f).replace(/\\/g, '/')).join(', ')}.`,
    '// Do not edit: change the sources in src/GenPages and run the build.',
    ...lines,
    '',
    ...jsonConsts.map((j) => `const ${j.name} = ${j.json};`),
    ...order.map((f) => `// ---- ${relative(root, f).replace(/\\/g, '/')}\n${bodies.get(f).trimEnd()}\n`),
  ];
  return parts.join('\n');
}

mkdirSync(resolve(root, 'dist'), { recursive: true });
for (const page of manifest.pages) {
  const out = bundle(resolve(root, page.file));
  writeFileSync(resolve(root, 'dist', `${page.key}.tsx`), out);
  const bindings = page.actions.map((name) => {
    const a = apis[name];
    if (!a) throw new Error(`${page.key}: unknown Custom API ${name}`);
    return { name, isFunction: false, displayName: a.displayName, parameterKinds: a.parameterKinds };
  });
  writeFileSync(resolve(root, 'dist', `${page.key}.actions.json`), JSON.stringify(bindings, null, 2));
  console.log(`built dist/${page.key}.tsx (${Math.round(out.length / 1024)} KB)`);
}
